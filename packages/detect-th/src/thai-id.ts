/**
 * เลขประจำตัวประชาชนไทย 13 หลัก
 *
 * หลักสุดท้ายคือหลักตรวจสอบ คำนวณจาก 12 หลักแรกโดยถ่วงน้ำหนักลดหลั่นจาก 13 ลงมา 2
 * แล้วเอาผลรวมหารเอาเศษด้วย 11
 *
 * หลักตรวจสอบคือสิ่งเดียวที่แยก "เลข 13 หลักที่เป็นเลขบัตรจริง" ออกจาก
 * "ตัวเลข 13 หลักอะไรก็ได้" — ถ้าไม่ตรวจ ทุกรหัสอ้างอิงยาว ๆ ในระบบจะกลายเป็นผลบวกลวง
 * เลขสุ่มสิบสามหลักผ่านสูตรนี้ราวหนึ่งในสิบเอ็ด จึงกรองทิ้งได้ประมาณ 91%
 *
 * ⚠️ ข้อจำกัดที่วัดแล้ว — สูตรนี้ไม่ได้แปลว่าเลขนั้นมีอยู่จริง
 * หลักที่สามมีน้ำหนัก 11 ซึ่งหารด้วย 11 ลงตัว จึงไม่มีผลต่อเศษเลย
 * **แก้หลักที่สามเป็นอะไรก็ได้ สูตรนี้จับไม่ได้เลยสักกรณี**
 * ส่วนหลักอื่นจับไม่ได้ราว 1.7% จากการที่เศษ 0 กับ 1 ให้หลักตรวจสอบเป็น 0 เหมือนกัน
 * ใช้ยืนยันตัวตนจริงไม่ได้ ใช้ได้แค่คัดกรองว่า "น่าจะเป็นเลขบัตร" เท่านั้น
 */

/** คำนวณหลักตรวจสอบจาก 12 หลักแรก คืน -1 ถ้าอินพุตไม่ใช่ตัวเลข 12 หลัก */
export function thaiIdCheckDigit(first12: string): number {
  if (!/^[0-9]{12}$/.test(first12)) return -1;
  let sum = 0;
  for (let i = 0; i < 12; i += 1) {
    sum += Number(first12[i]) * (13 - i);
  }
  return (11 - (sum % 11)) % 10;
}

/** ตรวจว่าเลข 13 หลักนี้ผ่านหลักตรวจสอบหรือไม่ */
export function isValidThaiId(value: string): boolean {
  const digits = value.replace(/[\s-]/g, "");
  if (!/^[0-9]{13}$/.test(digits)) return false;

  // เลขที่เป็นตัวเดียวกันทั้งหมดผ่านสูตรได้ แต่ไม่มีอยู่จริง
  if (/^(\d)\1{12}$/.test(digits)) return false;

  return thaiIdCheckDigit(digits.slice(0, 12)) === Number(digits[12]);
}

/**
 * สร้างเลขที่ผ่านหลักตรวจสอบจาก 12 หลักแรกที่กำหนดเอง
 *
 * มีไว้ให้เทสต์และตัวอย่างใช้ เพื่อจะได้ไม่ต้องเอาเลขบัตรของคนจริงมาใส่ในโค้ด
 */
export function makeThaiId(first12: string): string {
  const check = thaiIdCheckDigit(first12);
  if (check === -1) throw new Error("ต้องเป็นตัวเลข 12 หลัก");
  return `${first12}${check}`;
}
